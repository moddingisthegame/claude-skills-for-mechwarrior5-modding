#!/usr/bin/env python3
"""Runs every skill's evals/eval_set.json through the real Claude Code CLI to
measure trigger rate.

For each query, the model is shown every skill's name + description found
anywhere in the repo — not just the one skill under test — because the
failure mode this marketplace actually cares about is cross-triggering
between confusable siblings (Mercs vs. Clans, UE4 vs. UE5). Presenting only
one skill's description at a time would not catch that; a user with both
plugins installed sees all four at once, so that's the scenario evaluated.
See EVALS.md for the schema and design rationale.

Runs through `claude -p` (the CLI itself) rather than the raw Messages API,
specifically so a Claude subscription's CLAUDE_CODE_OAUTH_TOKEN (generated by
`claude setup-token`) can pay for these calls instead of per-token API
billing. Deliberately uses --safe-mode, not the generally-recommended --bare:
--bare never reads OAuth credentials or the system keychain (API-key auth
only), which would defeat the whole point here. --safe-mode disables the
same CLAUDE.md/skill/plugin/hook auto-discovery for a clean, isolated
session, while leaving auth working normally.

Requires CLAUDE_CODE_OAUTH_TOKEN or ANTHROPIC_API_KEY. If neither is set
(e.g. a contributor's fork without the secret, or a fork PR that can't see
repo secrets), this prints a notice and exits 0 rather than failing the
pipeline — structural validation already covers syntax/schema and runs
regardless. If a credential *is* set but invalid or expired (OAuth tokens
from `claude setup-token` are valid for ~1 year with no refresh), this fails
fast with a clear message instead of retrying all ~90 queries pointlessly.

Env vars:
  CLAUDE_CODE_OAUTH_TOKEN / ANTHROPIC_API_KEY   one required; skip (exit 0) if neither set
  EVAL_MODEL            model id or alias (default: haiku — always resolves to
                        the latest Haiku, e.g. currently claude-haiku-4-5-20251001)
  EVAL_RUNS             times to repeat each query, majority vote (default: 1)
  EVAL_PASS_THRESHOLD   per-skill minimum pass rate to succeed (default: 0.8)
"""
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FRONTMATTER_RE = re.compile(r"^---\r?\n(.*?)\r?\n---\r?\n", re.S)

MODEL = os.environ.get("EVAL_MODEL", "haiku")
RUNS = max(1, int(os.environ.get("EVAL_RUNS", "1")))
THRESHOLD = float(os.environ.get("EVAL_PASS_THRESHOLD", "0.8"))
CALL_TIMEOUT_SECONDS = 90
MAX_ATTEMPTS = 3


def discover_skills() -> dict[str, dict]:
    skills: dict[str, dict] = {}
    for skill_md in sorted((ROOT / "plugins").glob("*/skills/*/SKILL.md")):
        text = skill_md.read_text(encoding="utf-8")
        m = FRONTMATTER_RE.match(text)
        if not m:
            continue
        try:
            fm = yaml.safe_load(m.group(1))
        except yaml.YAMLError:
            continue
        if not isinstance(fm, dict) or "name" not in fm or "description" not in fm:
            continue
        skills[fm["name"]] = {"description": fm["description"], "dir": skill_md.parent}
    return skills


def build_system_prompt(skills: dict[str, dict]) -> str:
    lines = ["Skills available in this session (name: description):", ""]
    for name, info in sorted(skills.items()):
        lines.append(f"- {name}: {info['description']}")
    lines += [
        "",
        "Given the user's next message, decide which of the skills above (if "
        "any) you would invoke to help answer it, based only on their names "
        "and descriptions above — you have not read any skill's full "
        "instructions yet, only this one-line summary of each.",
    ]
    return "\n".join(lines)


def check_auth() -> tuple[bool, str]:
    """Returns (ok, message). ok=False with a non-empty message means a
    credential is present but not usable — a real failure, not a skip."""
    try:
        proc = subprocess.run(
            ["claude", "auth", "status"],
            capture_output=True,
            text=True,
            timeout=30,
        )
        status = json.loads(proc.stdout)
    except FileNotFoundError:
        return False, "the `claude` CLI is not installed / not on PATH"
    except (subprocess.TimeoutExpired, json.JSONDecodeError) as e:
        return False, f"could not determine auth status: {e}"
    if not status.get("loggedIn"):
        return False, "credential is set but `claude auth status` reports not logged in (expired or invalid token?)"
    return True, f"authenticated via {status.get('authMethod', '?')} ({status.get('subscriptionType', 'api')})"


def call_claude(system_prompt: str, user_message: str, skill_names: list[str]) -> tuple[dict, float]:
    """Runs `claude -p` once. Returns (structured_output, cost_usd). Raises on failure."""
    schema = json.dumps(
        {
            "type": "object",
            "properties": {
                "skills": {
                    "type": "array",
                    "items": {"type": "string", "enum": skill_names},
                }
            },
            "required": ["skills"],
        }
    )
    cmd = [
        "claude",
        "-p",
        user_message,
        "--safe-mode",
        "--tools",
        "",
        "--system-prompt",
        system_prompt,
        "--output-format",
        "json",
        "--json-schema",
        schema,
        "--no-session-persistence",
        "--model",
        MODEL,
    ]
    proc = subprocess.run(
        cmd, capture_output=True, text=True, timeout=CALL_TIMEOUT_SECONDS, cwd=ROOT
    )
    if proc.returncode != 0:
        raise RuntimeError(f"claude exited {proc.returncode}: {proc.stderr.strip()[:500]}")

    events = json.loads(proc.stdout)
    result_events = [e for e in events if e.get("type") == "result"]
    if not result_events:
        raise RuntimeError(f"no 'result' event in output: {proc.stdout[:500]}")
    result = result_events[-1]
    if result.get("is_error"):
        raise RuntimeError(f"claude reported an error: {str(result.get('result'))[:500]}")

    structured = result.get("structured_output")
    if structured is None:
        structured = json.loads(result["result"])
    return structured, float(result.get("total_cost_usd") or 0.0)


def run_skill_evals(skill_name, cases, system_prompt, sorted_skill_names):
    passed = 0
    failures = []
    cost = 0.0
    for case in cases:
        query, expected = case["query"], case["should_trigger"]
        hits = 0
        completed = 0
        for _ in range(RUNS):
            structured = None
            for attempt in range(MAX_ATTEMPTS):
                try:
                    structured, call_cost = call_claude(system_prompt, query, sorted_skill_names)
                    cost += call_cost
                    break
                except Exception as e:
                    if attempt == MAX_ATTEMPTS - 1:
                        print(f"::warning::giving up on '{skill_name}' query {query!r} after {MAX_ATTEMPTS} attempts: {e}")
                    else:
                        time.sleep((attempt + 1) * 3)
            if structured is None:
                continue
            completed += 1
            invoked_names = {s for s in structured.get("skills", []) if isinstance(s, str)}
            if (skill_name in invoked_names) == expected:
                hits += 1
            time.sleep(0.3)
        ok = completed > 0 and hits * 2 >= completed
        if ok:
            passed += 1
        else:
            failures.append((query, expected, hits, completed))
    return passed, failures, cost


def main() -> int:
    have_credential = bool(os.environ.get("CLAUDE_CODE_OAUTH_TOKEN") or os.environ.get("ANTHROPIC_API_KEY"))
    if not have_credential:
        print(
            "Neither CLAUDE_CODE_OAUTH_TOKEN nor ANTHROPIC_API_KEY is set — "
            "skipping eval run (structural validation already covers "
            "syntax/schema)."
        )
        return 0

    auth_ok, auth_msg = check_auth()
    if not auth_ok:
        print(f"::error::a credential is configured but unusable — {auth_msg}")
        return 1
    print(f"Auth check: {auth_msg}")

    skills = discover_skills()
    if not skills:
        print("::error::no skills discovered — did structural validation run first?")
        return 1

    system_prompt = build_system_prompt(skills)
    sorted_skill_names = sorted(skills)
    overall_failed = False
    grand_total_cost = 0.0

    print(f"Model: {MODEL}  |  runs/query: {RUNS}  |  pass threshold: {THRESHOLD:.0%}\n")

    for skill_name, info in sorted(skills.items()):
        eval_path = info["dir"] / "evals" / "eval_set.json"
        if not eval_path.is_file():
            continue
        cases = json.loads(eval_path.read_text(encoding="utf-8"))

        passed, failures, cost = run_skill_evals(skill_name, cases, system_prompt, sorted_skill_names)
        grand_total_cost += cost
        rate = passed / len(cases) if cases else 1.0
        status = "PASS" if rate >= THRESHOLD else "FAIL"
        print(f"[{status}] {skill_name}: {passed}/{len(cases)} ({rate:.0%})  cost: ${cost:.4f}")
        for query, expected, hits, runs in failures:
            print(f"    expected should_trigger={expected}, matched {hits}/{runs} run(s) — {query!r}")
        if rate < THRESHOLD:
            overall_failed = True
            print(f"::error::{skill_name} trigger-eval pass rate {rate:.0%} is below threshold {THRESHOLD:.0%}")
        print()

    print(f"Total cost this run: ${grand_total_cost:.4f}")
    return 1 if overall_failed else 0


if __name__ == "__main__":
    sys.exit(main())
